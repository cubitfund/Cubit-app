// Copy deployment records verbatim, including an optional mainnet launchpad and an optional mainnet launchpad v2. The
// committed copies let the app build alone. The generated import selects mainnet without requiring placeholders.
//   node scripts/sync-deployment.mjs          sync records and imports
//   node scripts/sync-deployment.mjs --check  check integrity without writing
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export function syncDeployments(source, destination, check = false) {
  const copies = new Map();
  for (const chainId of [1, 11155111]) {
    for (const launchpad of [false, true]) {
      const file = `${chainId}${launchpad ? ".launchpad" : ""}.json`;
      const from = join(source, file);
      if (!existsSync(from)) {
        if (chainId === 1 && launchpad) { copies.set(file, null); continue; }
        throw new Error(`missing ${from}: deployment record required`);
      }
      const text = readFileSync(from, "utf8");
      const record = JSON.parse(text);
      if (record.chainId !== chainId) throw new Error(`${file} belongs to chain ${record.chainId}`);
      // The prepared mainnet record predates launch verification. Never invent verification flags or relax the
      // checks for a launched market / launchpad. An explicit failed verification is always rejected.
      const prepared = chainId === 1 && !launchpad && record.release === "v1-v2-prepared" &&
        record.marketOpen === false && record.enabledFeatures === 0 &&
        record.runtimeVerified === undefined && record.broadcastVerified === undefined;
      if (!prepared && (record.runtimeVerified !== true || record.broadcastVerified !== true))
        throw new Error(`${file} is not a verified deployment`);
      copies.set(file, text);
    }
  }
  // Launchpad v2 (CubitForgeV2): optional on each chain until it is deployed, verified and promoted.
  for (const chainId of [1, 11155111]) {
    const v2File = `${chainId}.launchpad-v2.json`;
    const v2From = join(source, v2File);
    if (existsSync(v2From)) {
      const text = readFileSync(v2From, "utf8");
      const record = JSON.parse(text);
      if (record.chainId !== chainId) throw new Error(`${v2File} belongs to chain ${record.chainId}`);
      if (record.runtimeVerified !== true || record.broadcastVerified !== true) throw new Error(`${v2File} is not a verified deployment`);
      copies.set(v2File, text);
    } else copies.set(v2File, null);
  }
  const v2File = "1.launchpad-v2.json";
  copies.set("mainnet.ts", `// Generated by scripts/sync-deployment.mjs. Do not edit.
export { default as launchRecord } from "./1.json" with { type: "json" };
${copies.get("1.launchpad.json")
    ? 'export { default as launchpadRecord } from "./1.launchpad.json" with { type: "json" };'
    : "export const launchpadRecord = null;"}
${copies.get(v2File)
    ? 'export { default as launchpadV2Record } from "./1.launchpad-v2.json" with { type: "json" };'
    : "export const launchpadV2Record = null;"}
`);
  // Sepolia: a build with VITE_NETWORK=sepolia.
  copies.set("sepolia.ts", `// Generated by scripts/sync-deployment.mjs. Do not edit.
export { default as launchRecord } from "./11155111.json" with { type: "json" };
export { default as launchpadRecord } from "./11155111.launchpad.json" with { type: "json" };
${copies.get("11155111.launchpad-v2.json")
    ? 'export { default as launchpadV2Record } from "./11155111.launchpad-v2.json" with { type: "json" };'
    : "export const launchpadV2Record = null;"}
`);

  if (!check) mkdirSync(destination, { recursive: true });
  for (const [file, text] of copies) {
    const to = join(destination, file);
    if (check) {
      if (text === null ? existsSync(to) : !existsSync(to) || readFileSync(to, "utf8") !== text)
        throw new Error(`stale ${to}: run node scripts/sync-deployment.mjs`);
    } else if (text === null) rmSync(to, { force: true });
    else writeFileSync(to, text);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const check = process.argv.includes("--check");
  syncDeployments(join(root, "..", "contracts", "deployments"), join(root, "src", "chain", "deployments"), check);
  console.log(check ? "deployment copies are current" : "deployment copies synced");
}
